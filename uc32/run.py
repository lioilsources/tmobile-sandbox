#!/usr/bin/env python3
"""UC32 Czech RAG on profile B: Qwen3-Embedding-0.6B + bge-reranker-v2-m3 + Qwen3-30B-A3B over public laws.

  run.py --dir /cold/uc32 [--n 200]

Stages (each skipped when its output exists, so a rerun resumes):
  qa.jsonl       200 question/answer pairs generated by the LLM from sampled sections
  emb.npy        corpus embeddings
  results.jsonl  per question: retrieval ranks, answers (closed book, embedding top 5, reranked top 5), judge scores, latencies
  report.md      recall, accuracy, latency, CZK per query
"""
import argparse, json, random, re, statistics, time, urllib.request
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

import numpy as np

LLM, EMB = "http://127.0.0.1:8000/v1", "http://127.0.0.1:8002/v1"
RERANKER = "BAAI/bge-reranker-v2-m3"
CZK_PER_H = 55
QUOTA = {"Zákon č. 127/2005 Sb.": 40, "Zákon č. 634/1992 Sb.": 30, "Zákon č. 110/2019 Sb.": 25,
         "Zákon č. 262/2006 Sb.": 35, "Zákon č. 235/2004 Sb.": 30, "Zákon č. 89/2012 Sb.": 40}
QUERY_INSTRUCT = "Instruct: Given a question in Czech, retrieve the section of Czech law that answers it\nQuery: "


def post(url, body, timeout=300):
    req = urllib.request.Request(url, json.dumps(body).encode(), {"Content-Type": "application/json"})
    with urllib.request.urlopen(req, timeout=timeout) as r:
        return json.load(r)


def chat(prompt, max_tokens=400):
    r = post(LLM + "/chat/completions", {"model": "qwen3-30b-a3b", "temperature": 0, "max_tokens": max_tokens,
                                         "messages": [{"role": "user", "content": prompt}]})
    return r["choices"][0]["message"]["content"].strip()


def embed(texts):
    r = post(EMB + "/embeddings", {"model": "qwen3-embed", "input": texts})
    v = np.array([d["embedding"] for d in r["data"]], dtype=np.float32)
    return v / np.linalg.norm(v, axis=1, keepdims=True)


def parse_json(s):
    m = re.search(r"\{.*\}", s, re.S)
    return json.loads(m.group(0)) if m else None


GEN = """Níže je ustanovení českého zákona. Napiš jednu otázku, kterou by mohl položit běžný člověk nebo zákazník \
(ne právník) a na kterou toto ustanovení jednoznačně odpovídá. Otázka nesmí zmiňovat číslo paragrafu ani zákona \
a nesmí kopírovat formulace z textu. Pak napiš stručnou správnou odpověď (1–3 věty) podle textu.
Vrať jen JSON: {{"question": "...", "answer": "..."}}

{cite}
{text}"""

ANSWER = """Odpověz česky a stručně (1–3 věty) na otázku. {ctx}Pokud odpověď nevíš, napiš „Nevím“.

Otázka: {q}"""

JUDGE = """Porovnej odpověď s referenční odpovědí na otázku. Hodnoť věcnou shodu, ne styl.
2 = věcně správně a úplně, 1 = částečně správně, 0 = špatně nebo „Nevím“.
Vrať jen JSON: {{"score": 0|1|2}}

Otázka: {q}
Referenční odpověď: {ref}
Hodnocená odpověď: {ans}"""


def gen_qa(corpus, n, out):
    rnd = random.Random(32)
    picks = []
    for law, k in QUOTA.items():
        pool = [c for c in corpus if c["law"] == law and len(c["text"]) >= 200]
        picks += rnd.sample(pool, round(k * n / 200))

    def one(c):
        try:
            j = parse_json(chat(GEN.format(cite=c["cite"], text=c["text"][:3000])))
            return {"id": c["id"], "law": c["law"], "cite": c["cite"], "question": j["question"], "answer": j["answer"]}
        except Exception as e:
            print("qa fail", c["id"], e, flush=True)

    with ThreadPoolExecutor(8) as ex:
        rows = [r for r in ex.map(one, picks) if r]
    out.write_text("".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows))
    print("qa", len(rows), flush=True)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", required=True)
    ap.add_argument("--n", type=int, default=200)
    a = ap.parse_args()
    d = Path(a.dir)
    corpus = [json.loads(l) for l in open(d / "corpus.jsonl")]
    ids = [c["id"] for c in corpus]

    if not (d / "qa.jsonl").exists():
        gen_qa(corpus, a.n, d / "qa.jsonl")
    qa = [json.loads(l) for l in open(d / "qa.jsonl")]

    if not (d / "emb.npy").exists():
        t = time.time()
        E = np.concatenate([embed(["%s\n%s" % (c["cite"], c["text"]) for c in corpus[i:i + 32]])
                            for i in range(0, len(corpus), 32)])
        np.save(d / "emb.npy", E)
        print("embedded %d in %.0f s" % (len(E), time.time() - t), flush=True)
    E = np.load(d / "emb.npy")

    import torch
    from transformers import AutoModelForSequenceClassification, AutoTokenizer
    tok = AutoTokenizer.from_pretrained(RERANKER)
    rr = AutoModelForSequenceClassification.from_pretrained(RERANKER, torch_dtype=torch.float16).cuda().eval()

    def rerank(q, cand):
        with torch.no_grad():
            x = tok([[q, corpus[i]["text"]] for i in cand], padding=True, truncation=True, max_length=1024,
                    return_tensors="pt").to("cuda")
            s = rr(**x).logits.view(-1).float().cpu().numpy()
        return [cand[i] for i in np.argsort(-s)]

    def ctx(top):
        return "Použij jen tyto úryvky zákonů:\n\n" + "\n\n".join(
            "[%s]\n%s" % (corpus[i]["cite"], corpus[i]["text"][:2500]) for i in top) + "\n\n"

    done = set()
    res_path = d / "results.jsonl"
    if res_path.exists():
        done = {json.loads(l)["id"] for l in open(res_path)}
    with open(res_path, "a") as out:
        for q in qa:
            if q["id"] in done:
                continue
            gold = ids.index(q["id"])
            t0 = time.time()
            qv = embed([QUERY_INSTRUCT + q["question"]])[0]
            t1 = time.time()
            emb_rank = list(np.argsort(-(E @ qv))[:50])
            t2 = time.time()
            rr_rank = rerank(q["question"], emb_rank)
            t3 = time.time()
            ans_rr = chat(ANSWER.format(ctx=ctx(rr_rank[:5]), q=q["question"]))
            t4 = time.time()
            ans_emb = chat(ANSWER.format(ctx=ctx(emb_rank[:5]), q=q["question"]))
            ans_cb = chat(ANSWER.format(ctx="", q=q["question"]))
            score = {}
            for k, ans in (("closed", ans_cb), ("emb", ans_emb), ("rerank", ans_rr)):
                try:
                    score[k] = int(parse_json(chat(JUDGE.format(q=q["question"], ref=q["answer"], ans=ans), 50))["score"])
                except Exception:
                    score[k] = None
            pos = lambda r: r.index(gold) + 1 if gold in r else None
            row = {"id": q["id"], "law": q["law"], "rank_emb": pos(emb_rank), "rank_rr": pos(rr_rank),
                   "answers": {"closed": ans_cb, "emb": ans_emb, "rerank": ans_rr}, "score": score,
                   "ms": {"embed": (t1 - t0) * 1e3, "search": (t2 - t1) * 1e3, "rerank": (t3 - t2) * 1e3,
                          "answer": (t4 - t3) * 1e3, "total": (t4 - t0) * 1e3}}
            out.write(json.dumps(row, ensure_ascii=False) + "\n")
            out.flush()
    report(d, [json.loads(l) for l in open(res_path)])


def report(d, rows):
    n = len(rows)
    rec = lambda key, k: sum(1 for r in rows if r[key] and r[key] <= k) / n
    mrr = lambda key: sum(1 / r[key] for r in rows if r[key]) / n
    acc = lambda k: [r["score"][k] for r in rows if r["score"][k] is not None]
    lat = lambda k: sorted(r["ms"][k] for r in rows)
    p = lambda v, q: v[min(len(v) - 1, int(q * len(v)))]
    tot = lat("total")
    lines = ["# UC32 RAG nad českými zákony", "", "%d otázek, korpus %d paragrafů ze 6 zákonů (e-Sbírka, aktuální znění)." % (
        n, len(open(d / "corpus.jsonl").readlines())), "", "## Vyhledávání (gold = paragraf, ze kterého otázka vznikla)", "",
        "| | R@1 | R@5 | R@20 | R@50 | MRR |", "|---|---|---|---|---|---|"]
    for name, key in (("Qwen3-Embedding-0.6B", "rank_emb"), ("+ bge-reranker-v2-m3", "rank_rr")):
        lines.append("| %s | %.2f | %.2f | %.2f | %.2f | %.3f |" % (name, rec(key, 1), rec(key, 5), rec(key, 20), rec(key, 50), mrr(key)))
    lines += ["", "## Odpovědi (soudce Qwen3-30B-A3B, 0–2 body)", "", "| | průměr | správně (2) | špatně (0) |", "|---|---|---|---|"]
    for name, k in (("bez kontextu", "closed"), ("embedding top 5", "emb"), ("rerank top 5", "rerank")):
        s = acc(k)
        lines.append("| %s | %.2f | %.0f %% | %.0f %% |" % (name, statistics.mean(s), 100 * s.count(2) / len(s), 100 * s.count(0) / len(s)))
    lines += ["", "## Latence pipeline (rerank top 5, sériově, ms)", "", "| fáze | p50 | p95 |", "|---|---|---|"]
    for k in ("embed", "search", "rerank", "answer", "total"):
        v = lat(k)
        lines.append("| %s | %.0f | %.0f |" % (k, p(v, .5), p(v, .95)))
    lines += ["", "Cena při %d Kč/h za VM a sériovém zpracování: %.3f Kč/dotaz (p50). Souběžné dotazy cenu dál snižují." % (
        CZK_PER_H, CZK_PER_H * p(tot, .5) / 3.6e6), ""]
    (d / "report.md").write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
